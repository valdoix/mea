/**
 * Builds the single-file Mea server (ARCH-14): web app + server in one executable.
 *
 *   bun scripts/build-exe.ts                 → dist/mea.exe (Windows x64)
 *   bun scripts/build-exe.ts --target host   → dist/mea for this machine (handy for testing)
 *   bun scripts/build-exe.ts --hide-console  → Windows: no console window (for the background service)
 *
 * The web build is embedded through generated `with { type: "file" }` imports, so the exe needs
 * nothing next to it. Its data folder is `data/` beside the exe (or MEA_DATA_DIR).
 */
import { $ } from "bun";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const args = process.argv.slice(2);
const flag = (name: string) => args.includes(name);
const option = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const targetArg = option("--target") ?? "windows";
const target = targetArg === "host" ? null : targetArg === "windows" ? "bun-windows-x64" : targetArg;
const windows = target ? target.includes("windows") : process.platform === "win32";
const outfile = resolve(root, option("--outfile") ?? join("dist", windows ? "mea.exe" : "mea"));

const dist = join(root, "web", "dist");
const generated = join(root, "server", "src", "embedded-assets.ts");
const stub = `// Replaced by scripts/build-exe.ts while compiling mea.exe (ARCH-14), then restored.
// Running from source, the web app is served from web/dist instead.
export const assets: Record<string, string> = {};
`;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

console.log("Building the web app…");
await $`bunx vite build --config web/vite.config.ts`.cwd(root);

const files = walk(dist).filter((f) => !f.endsWith(".map"));
const lines = files.map((f, i) => `import a${i} from ${JSON.stringify(relative(join(root, "server", "src"), f).replaceAll("\\", "/"))} with { type: "file" };`);
const entries = files.map((f, i) => `  ${JSON.stringify(relative(dist, f).replaceAll("\\", "/"))}: a${i},`);
writeFileSync(generated, `// Generated by scripts/build-exe.ts. Do not edit or commit.\n${lines.join("\n")}\n\nexport const assets: Record<string, string> = {\n${entries.join("\n")}\n};\n`);

try {
  console.log(`Compiling ${relative(root, outfile)} (${files.length} web files embedded)…`);
  const cmd = ["bun", "build", "--compile", "--minify", "server/src/exe.ts", "--outfile", outfile];
  if (target) cmd.push(`--target=${target}`);
  if (windows && flag("--hide-console")) cmd.push("--windows-hide-console");
  await $`${cmd}`.cwd(root);
} finally {
  writeFileSync(generated, stub);
}

const mb = (statSync(outfile).size / 1024 / 1024).toFixed(1);
console.log(`✿ Built ${relative(root, outfile)} (${mb} MB). Data goes in a "data" folder next to it.`);
